-- ============================================================================
-- 170 — One pending photo per person
-- ============================================================================
--
-- Manage > Photos showed several pending photos of the same member. The upload
-- paths delete the previous pending row(s) from the client first, but RLS only
-- lets a user see and delete rows THEY submitted (20_phase8_photo_rls.sql:
-- photo_select  user_id = auth.uid() or is_admin();
-- photo_delete  (user_id = auth.uid() and status = 'pending') or is_admin()),
-- so a pending row someone else submitted for the same person (a coach for a
-- student, a member for themselves) is never seen or deleted, and the client
-- swallows any failure. 170 enforces it in the database instead.
--
-- What it is based on (repo):
--   01_schema.sql  photo_approvals (id, user_id = the submitter, photo_url,
--                  status text not null default 'pending'
--                    check (status in ('pending','approved','rejected')),
--                  submitted_at, approved_by_id, approved_at)
--   11_phase5.sql  + student_id, rejected_reason
--   16_phase7_5    + staff_id. One subject per row: staff_id, else student_id,
--                  else the submitter's login (user_id, both null)
--   41 / 167       trg_photo_approval_sync, AFTER UPDATE: publishes only when
--                  NEW.status = 'approved' and OLD.status <> 'approved'
--   42             trg_notify_photo_status_change, AFTER UPDATE OF status:
--                  notifies only on approved / rejected
--
-- 1. status may also be 'superseded': a pending photo replaced by a newer one
--    of the same person. Never 'approved', so nothing is published; never
--    'rejected', so nobody is told "Photo rejected". Final: a BEFORE UPDATE
--    guard refuses any status change away from it, so a superseded row can
--    never reach approved through sync's "anything -> approved" edge.
-- 2. BEFORE INSERT trigger: a new 'pending' row marks every other pending row
--    of the SAME subject superseded (same staff_id; else same student_id with
--    staff_id null; else same user_id with both null). A transaction lock per
--    subject keeps two uploads at the same moment from both staying pending.
-- 3. One time cleanup: for each subject with more than one pending row, the
--    newest (submitted_at, then id) stays pending, the rest become superseded.
--    Those rows are first copied to public._bak_photo_approvals_pending_20261025
--    (RLS on, no policies: not readable through the API).
--
-- Storage files of superseded rows are left in the avatars bucket by this
-- migration (no storage.objects change). Approval, rejection, _publish_person_
-- photo (167), remove_photo and the storage policies are unchanged. The photo
-- queue (loadPhotoQueue) reads status = 'pending' only, so superseded rows
-- leave it.
--
-- Rollback: 170_photo_one_pending_rollback.sql. Checks: 170_photo_one_pending_verify.sql.
-- ============================================================================

begin;

do $$
declare
  v_bad text; n int;
begin
  select string_agg(x.c, ', ') into v_bad
    from (values ('id'), ('user_id'), ('student_id'), ('staff_id'), ('photo_url'), ('status'), ('submitted_at')) x(c)
   where not exists (select 1 from information_schema.columns i
                      where i.table_schema = 'public' and i.table_name = 'photo_approvals' and i.column_name = x.c);
  if v_bad is not null then raise exception '170 preflight: photo_approvals is missing: %', v_bad; end if;
  select string_agg(distinct status, ', ') into v_bad
    from public.photo_approvals where status not in ('pending', 'approved', 'rejected', 'superseded');
  if v_bad is not null then raise exception '170 preflight: unexpected status values: % (stop and compare)', v_bad; end if;
  select count(*) into n from pg_constraint
   where conrelid = 'public.photo_approvals'::regclass and contype = 'c' and pg_get_constraintdef(oid) ~ '\mstatus\M';
  if n <> 1 then raise exception '170 preflight: expected one status check on photo_approvals, found %', n; end if;
  if not exists (select 1 from pg_trigger where tgname = 'trg_photo_approval_sync' and tgrelid = 'public.photo_approvals'::regclass) then
    raise exception '170 preflight: trigger trg_photo_approval_sync is missing';
  end if;
end $$;

-- 1. the status check (its name is generated by 01's inline check: looked up)
do $$
declare c text;
begin
  select conname into c from pg_constraint
   where conrelid = 'public.photo_approvals'::regclass and contype = 'c' and pg_get_constraintdef(oid) ~ '\mstatus\M';
  execute format('alter table public.photo_approvals drop constraint %I', c);
end $$;
alter table public.photo_approvals
  add constraint photo_approvals_status_check check (status in ('pending', 'approved', 'rejected', 'superseded'));

-- the subject of a row: staff, else student, else the submitter's login
create or replace function public._photo_subject_key(p_staff uuid, p_student uuid, p_user uuid)
returns text
language sql
immutable
set search_path = public
as $$
  select case when p_staff is not null then 'staff:' || p_staff::text
              when p_student is not null then 'student:' || p_student::text
              else 'user:' || coalesce(p_user::text, '') end
$$;

-- 3. the one time cleanup, as a function so the verify runs the same code
create or replace function public._photo_supersede_duplicates()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare n int;
begin
  with ranked as (
    select id, row_number() over (partition by public._photo_subject_key(staff_id, student_id, user_id)
                                  order by submitted_at desc, id desc) as rn
      from public.photo_approvals
     where status = 'pending')
  update public.photo_approvals a set status = 'superseded'
    from ranked r
   where a.id = r.id and r.rn > 1;
  get diagnostics n = row_count;
  return n;
end;
$$;

create table if not exists public._bak_photo_approvals_pending_20261025 as
  select a.* from public.photo_approvals a
   where a.status = 'pending'
     and exists (select 1 from public.photo_approvals b
                  where b.status = 'pending' and b.id <> a.id
                    and public._photo_subject_key(b.staff_id, b.student_id, b.user_id)
                      = public._photo_subject_key(a.staff_id, a.student_id, a.user_id));
alter table public._bak_photo_approvals_pending_20261025 enable row level security;
revoke all on public._bak_photo_approvals_pending_20261025 from anon, authenticated;

do $$
declare n int;
begin
  n := public._photo_supersede_duplicates();
  raise notice '170: % older pending photo(s) marked superseded (backup: _bak_photo_approvals_pending_20261025)', n;
end $$;

-- 2. a new pending row supersedes the subject's other pending rows
create or replace function public._photo_supersede_pending()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare v_key text;
begin
  if NEW.status is distinct from 'pending' then
    return NEW;
  end if;
  v_key := public._photo_subject_key(NEW.staff_id, NEW.student_id, NEW.user_id);
  perform pg_advisory_xact_lock(hashtext('photo_one_pending'), hashtext(v_key));
  update public.photo_approvals a
     set status = 'superseded'
   where a.status = 'pending'
     and public._photo_subject_key(a.staff_id, a.student_id, a.user_id) = v_key;
  return NEW;
end;
$$;

drop trigger if exists trg_photo_one_pending on public.photo_approvals;
create trigger trg_photo_one_pending
  before insert on public.photo_approvals
  for each row
  execute function public._photo_supersede_pending();

-- superseded is final (nothing may approve or reopen it)
create or replace function public._photo_superseded_is_final()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if OLD.status = 'superseded' and NEW.status is distinct from 'superseded' then
    raise exception 'photo % was replaced by a newer photo', OLD.id using errcode = 'check_violation';
  end if;
  return NEW;
end;
$$;

drop trigger if exists trg_photo_superseded_final on public.photo_approvals;
create trigger trg_photo_superseded_final
  before update of status on public.photo_approvals
  for each row
  execute function public._photo_superseded_is_final();

revoke all on function public._photo_subject_key(uuid, uuid, uuid) from public, anon, authenticated;
revoke all on function public._photo_supersede_duplicates() from public, anon, authenticated;
revoke all on function public._photo_supersede_pending() from public, anon, authenticated;
revoke all on function public._photo_superseded_is_final() from public, anon, authenticated;

commit;
