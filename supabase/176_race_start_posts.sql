-- ============================================================================
-- 176 — Race start posts (Phase A: database only)
-- ============================================================================
-- When a race starts, every adult division gets one Wall post with a line
-- from a fixed list. Nothing in the app reads it yet (Phase B).
--
--   1. public.competition_start_lines: the 20 lines (RLS on, no policies).
--   2. public.competition_start_posts: one row per adult division and race
--      period (UNIQUE (division_id, period_from)); its id is the Oss target.
--   3. public._competition_start_post_due(p_today): inserts the posts due on
--      p_today, plus any missed on p_today - 1 and p_today - 2 (start_on = the
--      real start day; nothing older). Idempotent; returns the count inserted.
--        * event: status 'active' and starts_on = the day; period starts_on..ends_on.
--        * monthly: the day is the 1st, status 'active'; period = that month.
--          Skipped in a unit with an active event (a division there) where
--          starts_on <= day + 7 and coalesce(finale_on, ends_on) >= day.
--          A race resuming mid-month never posts (only the 1st does).
--        * drafts never post, kids never post.
--        * line: the active line used fewest times, then least recently used
--          (never used first), then id. One insert at a time, by unit name, so
--          two units on the same day get different lines.
--   4. The schedule: 'race-start-posts', 05:00 Sydney every day. 172's
--      mechanism: pg_cron runs in GMT ('0 18,19 * * *' = 05:00 AEDT / 04:00
--      and 05:00 AEST) and SQL decides the Sydney day
--      (_competition_start_post_day: null before 05:00 Sydney). In AEDT the
--      19:00 UTC run (06:00) finds nothing left to insert.
--   5. public.competition_start_posts_feed(): the posts for the Wall.
--   6. Oss: target type 'race_start' (toggle_oss list and branch,
--      _race_start_visible, a wall_reactions SELECT policy). No notifications
--      (172 sends none for Oss either).
--   7. Privileges: the feed to authenticated only; tables and the job's
--      functions closed to anon and authenticated.
--
-- toggle_oss: only the type list and one new branch change; the rest is the
-- live text (pg_get_functiondef, 28 Oct 2026, body md5 0b4a0f1bd53f0c75d680eb83690e1051 = 172's).
-- Owner, grants, SECURITY DEFINER and search_path are checked unchanged.
--
-- Rollback: 176_race_start_posts_rollback.sql. Checks: 176_race_start_posts_verify.sql.
--   psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f supabase/176_race_start_posts.sql
-- ============================================================================

