-- ---------------------------------------------------------------------------
-- 3. What is due
-- ---------------------------------------------------------------------------
create or replace function public._competition_start_post_due(p_today date)
returns integer
language plpgsql
volatile
security definer
set search_path = public
as $$
declare
  v_n    integer := 0;
  v_line smallint;
  r      record;
begin
  if p_today is null then
    raise exception 'p_today is required' using errcode = 'invalid_parameter_value';
  end if;
  -- one run at a time (the cron job and a hand call): the line choice reads
  -- what the previous insert wrote
  perform pg_advisory_xact_lock(hashtext('public._competition_start_post_due'));

  for r in
    with days as (
      -- today and the two days before it (missed runs); nothing older
      select (p_today - k)::date as d from generate_series(0, 2) k
    ), due as (
      -- an event starts
      select dy.d as start_on, c.id as competition_id, dv.id as division_id, dv.unit_id,
             c.starts_on as period_from, c.ends_on as period_to
        from days dy
        join public.competitions c on c.kind = 'event' and c.status = 'active' and c.starts_on = dy.d
        join public.competition_divisions dv on dv.competition_id = c.id and dv.audience = 'adult'
      union all
      -- a month starts (only the 1st), unless an event is about to start or
      -- still runs in that unit
      select dy.d, c.id, dv.id, dv.unit_id,
             dy.d, (dy.d + interval '1 month' - interval '1 day')::date
        from days dy
        join public.competitions c on c.kind = 'monthly' and c.status = 'active'
        join public.competition_divisions dv on dv.competition_id = c.id and dv.audience = 'adult'
       where extract(day from dy.d) = 1
         and not exists (
               select 1
                 from public.competitions e
                 join public.competition_divisions ed on ed.competition_id = e.id
                where e.kind = 'event' and e.status = 'active'
                  and ed.unit_id = dv.unit_id
                  and e.starts_on <= dy.d + 7
                  and coalesce(e.finale_on, e.ends_on) >= dy.d)
    )
    select due.*
      from due
      join public.units u on u.id = due.unit_id
     where not exists (select 1 from public.competition_start_posts p
                        where p.division_id = due.division_id and p.period_from = due.period_from)
     order by due.start_on, u.name, u.id, due.competition_id, due.division_id
  loop
    -- fewest uses, then least recently used (never used first), then id
    select l.id into v_line
      from public.competition_start_lines l
      left join public.competition_start_posts p on p.line_id = l.id
     where l.active
     group by l.id
     order by count(p.id), max(p.published_at) nulls first, l.id
     limit 1;
    if v_line is null then
      raise exception '176: no active race start line' using errcode = 'no_data_found';
    end if;
    insert into public.competition_start_posts
      (competition_id, division_id, unit_id, period_from, period_to, start_on, line_id)
    values (r.competition_id, r.division_id, r.unit_id, r.period_from, r.period_to, r.start_on, v_line)
    on conflict (division_id, period_from) do nothing;
    if found then
      v_n := v_n + 1;
    end if;
  end loop;
  return v_n;
end;
$$;

-- ---------------------------------------------------------------------------
-- 4. The schedule's Sydney day: null before 05:00 Sydney (172's way of
--    keeping local time in SQL; pg_cron runs in GMT)
-- ---------------------------------------------------------------------------
create or replace function public._competition_start_post_day(p_now timestamptz)
returns date
language sql
stable
set search_path = public
as $$
  select case when (p_now at time zone 'Australia/Sydney')::time >= time '05:00'
              then (p_now at time zone 'Australia/Sydney')::date end
$$;

-- ---------------------------------------------------------------------------
-- 5. The Wall feed
-- ---------------------------------------------------------------------------
-- Can the caller see (and Oss) this post? Never a draft, same unit unless the
-- caller owns units (172's _month_champions_visible rule). Posts are adults only.
create or replace function public._race_start_visible(p_target uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
      from public.competition_start_posts p
      join public.competitions c on c.id = p.competition_id
     where p.id = p_target
       and c.status <> 'draft'
       and ( public.is_unit_owner_any() or p.unit_id = public.current_unit() ))
$$;

create or replace function public.competition_start_posts_feed()
returns table (
  id               uuid,
  competition_id   uuid,
  competition_name text,
  kind             text,
  unit_id          uuid,
  division_id      uuid,
  division_label   text,
  start_on         date,
  period_from      date,
  period_to        date,
  finale_on        date,
  prize_places     integer,
  line             text,
  published_at     timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if coalesce(public.current_status(), '') <> 'approved' then
    raise exception 'not allowed' using errcode = 'insufficient_privilege';
  end if;
  return query
    select p.id, c.id, c.name::text, c.kind::text, p.unit_id, p.division_id, d.label::text,
           p.start_on, p.period_from, p.period_to,
           case when c.kind = 'event' then c.finale_on end,
           case when c.kind = 'event' and jsonb_typeof(c.prizes) = 'array' then jsonb_array_length(c.prizes) else 0 end,
           l.line, p.published_at
      from public.competition_start_posts p
      join public.competitions c on c.id = p.competition_id
      join public.competition_divisions d on d.id = p.division_id
      join public.competition_start_lines l on l.id = p.line_id
     where c.status <> 'draft'
       and ( public.is_unit_owner_any() or p.unit_id = public.current_unit() )
     order by p.published_at desc, p.id;
end;
$$;

-- ---------------------------------------------------------------------------
-- 6. Oss: 'race_start' (toggle_oss: the type list and one branch)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.toggle_oss(p_target_type text, p_target_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_uid uuid := auth.uid();
  v_ok boolean; v_exist uuid; v_count integer; v_react boolean;
begin
  if v_uid is null then raise exception 'not authenticated'; end if;
  if public.current_status() <> 'approved' then raise exception 'not approved'; end if;
  if public.current_role() not in ('student','instructor') then raise exception 'not allowed'; end if;
  if p_target_type not in ('promotion','post','member','champions','month_champions','race_start') then raise exception 'unsupported target type'; end if;

  if p_target_type = 'promotion' then
    select true into v_ok
    from public.promotions p
    join public.students s on s.id = p.student_id
    where p.id = p_target_id and s.prog = 'adult'
      and ( public.is_unit_owner_any() or s.unit_id = public.current_unit() )
    limit 1;
  elsif p_target_type = 'member' then
    -- A welcome card. Same visibility rule as a promotion: adult only, so a
    -- child is never reactable, and same unit unless the caller owns units.
    select true into v_ok
    from public.students s
    where s.id = p_target_id and s.prog = 'adult' and s.active is true
      and ( public.is_unit_owner_any() or s.unit_id = public.current_unit() )
    limit 1;
  elsif p_target_type = 'champions' then
    -- 161: a Cup champions card (target = the adult division). Adults only, a
    -- published event, same unit unless the caller owns units.
    select true into v_ok
    from public.competition_divisions d
    join public.competitions c on c.id = d.competition_id
    where d.id = p_target_id and d.audience = 'adult'
      and c.kind = 'event' and c.published_at is not null
      and ( public.is_unit_owner_any() or d.unit_id = public.current_unit() )
    limit 1;
  elsif p_target_type = 'month_champions' then
    -- 172: a Monthly race champions card (target = _month_champions_target of
    -- the adult division and the month). Adults only, a published month, same
    -- unit unless the caller owns units.
    v_ok := public._month_champions_visible(p_target_id);
  elsif p_target_type = 'race_start' then
    -- 176: a race start post (target = competition_start_posts.id). Adult
    -- divisions only, never a draft, same unit unless the caller owns units.
    v_ok := public._race_start_visible(p_target_id);
  else
    select true into v_ok
    from public.posts po
    where po.id = p_target_id and po.active is true
      and ( public.is_unit_owner_any() or po.unit_id = public.current_unit() )
    limit 1;
  end if;
  if v_ok is not true then raise exception 'target not visible'; end if;

  select id into v_exist from public.wall_reactions
  where target_type = p_target_type and target_id = p_target_id
    and reactor_user_id = v_uid and kind = 'oss';

  if v_exist is not null then
    delete from public.wall_reactions where id = v_exist;
    v_react := false;
  else
    insert into public.wall_reactions(target_type, target_id, reactor_user_id, kind)
    values (p_target_type, p_target_id, v_uid, 'oss');
    v_react := true;
  end if;

  select count(*) into v_count from public.wall_reactions
  where target_type = p_target_type and target_id = p_target_id and kind = 'oss';

  return jsonb_build_object('count', v_count, 'reacted', v_react);
end $function$;

drop policy if exists wall_reactions_select_race_start on public.wall_reactions;
create policy wall_reactions_select_race_start on public.wall_reactions for select using (
  target_type = 'race_start' and public.current_status() = 'approved'
  and ( public.current_role() = any (array['student','instructor']) or public.is_admin() )
  and public._race_start_visible(wall_reactions.target_id));

do $$
begin
  if md5((select prosrc from pg_proc where oid = to_regprocedure('public.toggle_oss(text, uuid)'))) <> '797d7bf7673a92239b40cfb963bbc894' then
    raise exception '176: toggle_oss body is not the expected text';
  end if;
  if not exists (select 1 from pg_proc p, acl176 a
                  where p.oid = to_regprocedure('public.toggle_oss(text, uuid)')
                    and p.proowner = a.proowner and p.proacl::text is not distinct from a.acl
                    and p.prosecdef = a.prosecdef and p.provolatile = a.provolatile
                    and p.proconfig::text is not distinct from a.cfg) then
    raise exception '176: owner, grants, security or search_path of toggle_oss changed';
  end if;
end $$;

